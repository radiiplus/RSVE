package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

var (
	sourcePath = flag.String("source", "source/develop/contracts.go", "pinned Bor contracts.go path")
	outputPath = flag.String("out", "internal/boradapter/pairing.go", "adapter output path")
)

func main() {
	flag.Parse()

	src, err := os.ReadFile(*sourcePath)
	check(err)

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, *sourcePath, src, parser.ParseComments)
	check(err)

	wantedFuncs := map[string]bool{
		"Run":                        false,
		"decodePointG1":              false,
		"decodePointG2":              false,
		"decodeBLS12381FieldElement": false,
	}
	wantedErrors := map[string]bool{
		"errBLS12381InvalidInputLength":          false,
		"errBLS12381InvalidFieldElementTopBytes": false,
		"errBLS12381G1PointSubgroup":             false,
		"errBLS12381G2PointSubgroup":             false,
	}
	hasPairingType := false
	var declarations []string

	for _, decl := range file.Decls {
		include := false
		switch d := decl.(type) {
		case *ast.GenDecl:
			if d.Tok == token.TYPE {
				for _, spec := range d.Specs {
					if ts, ok := spec.(*ast.TypeSpec); ok && ts.Name.Name == "bls12381Pairing" {
						hasPairingType = true
						include = true
					}
				}
			}
			if d.Tok == token.VAR {
				for _, spec := range d.Specs {
					vs, ok := spec.(*ast.ValueSpec)
					if !ok {
						continue
					}
					for _, name := range vs.Names {
						if _, wanted := wantedErrors[name.Name]; wanted {
							wantedErrors[name.Name] = true
							include = true
						}
					}
				}
			}
		case *ast.FuncDecl:
			if d.Recv == nil {
				if _, wanted := wantedFuncs[d.Name.Name]; wanted {
					wantedFuncs[d.Name.Name] = true
					include = true
				}
			} else if d.Name.Name == "Run" && receiverName(d.Recv) == "bls12381Pairing" {
				wantedFuncs["Run"] = true
				include = true
			}
		}
		if include {
			declarations = append(declarations, string(src[fset.Position(declarationStart(decl)).Offset:fset.Position(decl.End()).Offset]))
		}
	}

	checkMissing("bls12381Pairing type", hasPairingType)
	for name, found := range wantedFuncs {
		checkMissing(name, found)
	}
	for name, found := range wantedErrors {
		checkMissing(name, found)
	}

	var out strings.Builder
	out.WriteString("// Code generated by tools/extract_pairing.go; DO NOT EDIT.\n")
	out.WriteString("// Source: github.com/0xPolygon/bor core/vm/contracts.go at cefbcfd4078e7a6cdb8e7642bc26e3589e05e7ab.\n\n")
	out.WriteString("package boradapter\n\n")
	out.WriteString("import (\n\t\"errors\"\n\tbls12381 \"github.com/consensys/gnark-crypto/ecc/bls12-381\"\n\t\"github.com/consensys/gnark-crypto/ecc/bls12-381/fp\"\n)\n\n")
	for _, declaration := range declarations {
		out.WriteString(declaration)
		out.WriteString("\n\n")
	}
	out.WriteString("// RunPairing exposes the extracted precompile path to standalone callers.\n")
	out.WriteString("func RunPairing(input []byte) ([]byte, error) {\n\treturn (&bls12381Pairing{}).Run(input)\n}\n")

	formatted, err := format.Source([]byte(out.String()))
	check(err)
	check(os.MkdirAll(filepath.Dir(*outputPath), 0o755))
	check(os.WriteFile(*outputPath, formatted, 0o644))
}

func receiverName(list *ast.FieldList) string {
	if len(list.List) != 1 {
		return ""
	}
	expr := list.List[0].Type
	if star, ok := expr.(*ast.StarExpr); ok {
		expr = star.X
	}
	if ident, ok := expr.(*ast.Ident); ok {
		return ident.Name
	}
	return ""
}

func declarationStart(decl ast.Decl) token.Pos {
	switch d := decl.(type) {
	case *ast.GenDecl:
		if d.Doc != nil {
			return d.Doc.Pos()
		}
	case *ast.FuncDecl:
		if d.Doc != nil {
			return d.Doc.Pos()
		}
	}
	return decl.Pos()
}

func checkMissing(name string, found bool) {
	if !found {
		fmt.Fprintf(os.Stderr, "required declaration not found: %s\n", name)
		os.Exit(1)
	}
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
